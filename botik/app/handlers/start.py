from aiogram import Router, types
from aiogram.filters import Command

router = Router()

@router.message(Command("start"))
async def start(message: types.Message):
    await message.answer(
        "👋 Привет!\n\n"
        "Это бот сервиса вишлистов и подарков 🎁\n\n"
        "Здесь ты можешь:\n"
        "• создавать и управлять своими вишлистами\n"
        "• добавлять желания и делиться ими с друзьями\n"
        "• подписываться на друзей и их вишлисты\n"
        "• получать напоминания о днях рождения\n"
        "• получать персональные рекомендации, что подарить\n\n"
        "📱 Мини-приложение\n"
        "Основная работа с вишлистами происходит в Telegram Mini App:\n"
        "— удобный интерфейс\n"
        "— профили пользователей\n"
        "— вишлисты и желания\n"
        "— настройки приватности\n\n"
        "🤖 Что умеет бот:\n"
        "• напоминать о днях рождения\n"
        "• уведомлять о подписках и запросах доступа\n"
        "• присылать персональные подборки подарков\n\n"
        "📌 Доступные команды:\n"
        "/start — информация о боте\n"
        "/help — список команд\n"
        "/what — получить идеи подарков\n\n"
        "👉 Чтобы начать, открой мини-приложение или напиши:\n"
        "«Что подарить»"
    )
